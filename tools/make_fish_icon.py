"""Rebuild the Windows ICO and matching Direct2D curves. Requires Pillow only for artwork edits."""
from pathlib import Path
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
# Closed cubic contours: body & forked tail, the curved page/gill, and eye (negative space).
paths = [
    [(25,47), (36,30,54,20,72,24), (85,26,94,35,99,45), (101,49,99,52,96,55),
     (86,68,71,78,54,76), (40,75,32,66,25,56), (18,60,12,66,6,67),
     (3,68,2,66,3,63), (7,53,6,46,2,37), (1,34,3,32,6,33), (15,36,20,43,25,47)],
    [(64,31), (56,46,58,60,66,69), (50,62,48,43,64,31)],
    [(86,42), (86,48,77,48,77,42), (77,36,86,36,86,42)],
]

def points(path):
    x,y=path[0]
    yield x,y
    for a,b,c,d,e,f in path[1:]:
        for j in range(1,33):
            t=j/32; u=1-t
            yield (u**3*x+3*u*u*t*a+3*u*t*t*c+t**3*e,
                   u**3*y+3*u*u*t*b+3*u*t*t*d+t**3*f)
        x,y=e,f

def icon(size):
    # Render larger than target, with a slightly larger mark for tray sizes.
    n=max(384,size*4); ss=n/100; pad=9 if size<=32 else 12
    mask=Image.new('L',(n,n),0); dm=ImageDraw.Draw(mask)
    dm.rounded_rectangle((2*ss,2*ss,n-2*ss-1,n-2*ss-1),radius=24*ss,fill=255)
    im=Image.new('RGBA',(n,n)); draw=ImageDraw.Draw(im)
    for y in range(n):
        t=y/(n-1)
        draw.line((0,y,n,y),fill=tuple(round(a+(b-a)*t) for a,b in zip((66,87,106),(32,47,63)))+(255,))
    mark=Image.new('L',im.size,0); d=ImageDraw.Draw(mark)
    for i,path in enumerate(paths):
        d.polygon([((pad+x*(1-2*pad/100))*ss,(pad+y*(1-2*pad/100))*ss) for x,y in points(path)],
                  fill=0 if i else 255)
    im.paste((232,239,245,255),(0,0,n,n),mark);im.putalpha(mask)
    return im.resize((size,size),Image.Resampling.LANCZOS)

sizes=[16,20,24,32,40,48,64,128,256]
images=[icon(s) for s in sizes]
images[-1].save(ROOT/'assets'/'fish.ico',sizes=[(s,s) for s in sizes],append_images=images[:-1])
lines=['// SPDX-License-Identifier: GPL-3.0-or-later', '// Generated by tools/make_fish_icon.py; original artwork for FishReader.',
       '#pragma once','#include <d2d1.h>','namespace leaf {','inline void fishContours(ID2D1GeometrySink* sink) {',
       '    sink->SetFillMode(D2D1_FILL_MODE_ALTERNATE);']
for start,*segments in paths:
    lines.append('    sink->BeginFigure({%d,%d}, D2D1_FIGURE_BEGIN_FILLED);'%start)
    for seg in segments:
        lines.append('    sink->AddBezier(D2D1_BEZIER_SEGMENT{{%d,%d},{%d,%d},{%d,%d}});'%seg)
    lines.append('    sink->EndFigure(D2D1_FIGURE_END_CLOSED);')
lines+=['}','} // namespace leaf','']
(ROOT/'src'/'ui'/'fish_mark.hpp').write_text('\n'.join(lines),encoding='utf-8')
